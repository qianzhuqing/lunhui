// 增益／异常两类状态图标的**共用徽章骨架**（32×32）。
//
// 为什么单开一份：`status.js`（异常 4）与 `buff.js`（增益 19）是两族图，骨架却是同一段——
// 亮色圆底（下缘压暗一档做体积）＋ 左上受光 ＋ 墨线勾边，记号画在勾边之后。
// 两族各抄一份的话，哪天调圆底半径或受光位置只会改到一族，而它们
// **并排出现在同一个 chip 列表里**（`battle_screen._make_effect_chip()`），一眼就看出不像一套。
//
// 与武学／物品那套**反着来**：那些是「压暗圆底 ＋ 亮记号」（列表里排一行，底要沉下去、不抢字）；
// 状态这两族是「亮色圆底 ＋ 深记号」——chip 本身就小，亮底先在深色面板上抓住眼睛，
// 再靠记号分辨是哪一个（15 §二／§4.3）。

"use strict";

const { Canvas, hex, shade } = require("./pixel");

const S = 32;

/**
 * 状态徽章：亮色圆底（下缘压暗一档做体积）＋ 一个深色记号 ＋ 墨线边。
 * **两族共用这一段骨架**（15 §4.3「同一类别内构图取齐」），只换颜色与 `draw` 的记号。
 *
 * `draw(c, mark, light)` 拿到的是**近黑**的记号色与那口受光亮色：记号一律用近黑，
 * 而不是"同色系的深版"——第一版用了各自色系的暗色，结果绿底上的暗绿、橙底上的暗橙
 * 全糊在一起。**彩底上的记号只有明度差够大才认得出**，色相由圆底承担就够了。
 *
 * 记号可用的**安全区**是中心 (15.5, 15) 那个 rx 10.5／ry 10 的椭圆内（`badge` 最后一步
 * 用它把受光重铺一遍）——画到外面会踩亮边，这一族的记号越界就会糊掉。
 */
function badge(color, light, draw) {
  const c = new Canvas(S, S);
  c.disk(15.5, 16, 12.5, hex(shade(color, -0.3)));  // 下缘：压暗一档
  c.disk(15.5, 15, 12.5, hex(color));               // 圆底
  c.disk(13.5, 11.5, 6, hex(light));                // 左上受光
  c.ellipse(15.5, 15, 10.5, 10, hex(color));
  c.edge();                                         // 外描边走 pixel.EDGE（2026-10-04 换肤统一）
  // 记号**画在勾边之后**：勾边会给近黑的记号各包一圈墨、挨得近的还会连成一片
  // （第一版中毒那三粒泡就是这么糊成一坨的）；亮底上的深记号本来不需要那圈墨。
  draw(c, hex("#20262A"), hex(light));
  return c;
}

module.exports = { badge, S };
